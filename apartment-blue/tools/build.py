#!/usr/bin/env python3
"""Build the libadwaita stylesheets and native window frames."""

import argparse
import json
from pathlib import Path
from textwrap import indent

from window_frames import native_frames


ROOT = Path(__file__).resolve().parents[1]
THEME = ROOT / "themes/Apartment-Blue"
NOTICE = "/* Generated by tools/build.py. */\n"
DARK_DEFAULTS = '@import url("resource:///org/gnome/Adwaita/styles/defaults-dark.css");\n\n'


def stylesheets():
    colors = json.loads((ROOT / "palette/libadwaita.json").read_text(encoding="utf-8"))
    legacy = "".join(f"@define-color {name} {value};\n" for name, value in colors.items())
    variables = "".join(f"  --{name.replace('_', '-')}: {value};\n"
                        for name, value in colors.items())
    modern = "window, popover {\n" + variables + "}\n"
    chrome = "\n".join((THEME / name).read_text(encoding="utf-8")
                       for name in ("chrome.css", "window-controls.css", "gtk4-chrome.css"))
    yield "libadwaita-override/legacy.css", legacy
    yield "libadwaita-override/modern.css", modern
    yield "libadwaita-1.5/defaults-dark.css", DARK_DEFAULTS + legacy
    yield "libadwaita-1.7/defaults-dark.css", DARK_DEFAULTS + ":root {\n" + variables + "}\n"
    chrome = chrome.replace('url("titlebuttons/', 'url("../titlebuttons/')
    yield "libadwaita-1.9/gtk.css", (
        '@import url("resource:///org/gnome/Adwaita/styles/gtk.css");\n\n'
        "@media (prefers-color-scheme: dark) and (prefers-contrast: no-preference) {\n"
        + indent(modern + "\n" + chrome, "  ") + "}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the files without changing them")
    args = parser.parse_args()
    stale = []
    assets = [(f"Apartment-Blue/{name}", NOTICE + css) for name, css in stylesheets()]
    assets.extend(native_frames(THEME))
    for name, asset in assets:
        path = THEME.parent / name
        content = asset.encode("utf-8")
        if args.check:
            if not path.is_file() or path.read_bytes() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        parser.exit(1, "Run python3 tools/build.py. Outdated theme files:\n" + "\n".join(stale) + "\n")


if __name__ == "__main__":
    main()
