"""Draw the native frames with the same colors and SVGs as the GTK header."""

import re
from xml.etree import ElementTree as ET


HEIGHT = 32
BUTTON = 22
GLYPH = 12
SVG = "http://www.w3.org/2000/svg"
ET.register_namespace("", SVG)

EXTRA_GLYPHS = {
    "menu": "M3 4h6m-6 2h6m-6 2h6",
    "shade": "m3.5 7 2.5-2.5L8.5 7",
    "unshade": "m3.5 5 2.5 2.5L8.5 5",
    "stick": "M6 3.5v5m-2-3h4",
    "unstick": "M4 6h4",
    "above": "M3.5 4h5m-5 3 2.5-2L8.5 7",
    "unabove": "M3.5 8h5m-5-3 2.5 2L8.5 5",
}
CONTROLS = ("menu", "minimize", "maximize", "close", "shade", "unshade",
            "above", "unabove", "stick", "unstick")
BUTTONS = {
    "close": ("M4.4 4.4l3.2 3.2m0-3.2L4.4 7.6", "#cf8a8a", "#604447"),
    "minimize": ("M4 6h4", "#9bb09d", "#435548"),
    "maximize": ("M4 4h4v4H4z", "#c3a173", "#5c4d3c"),
    "restore": ("M3.5 5h3.5v3.5H3.5zM5 5V3.5h3.5V7H7", "#c3a173", "#5c4d3c"),
}
GENERATED = "<!-- Generated by tools/build.py. -->"


def title_colors(theme):
    css = (theme / "chrome.css").read_text(encoding="utf-8")
    gradients = re.findall(r"linear-gradient\(to bottom, (#[\da-f]{6}), (#[\da-f]{6})\)", css)
    edges = re.findall(r"box-shadow: inset 0 1px (#[\da-f]{6}), inset 0 -1px (#[\da-f]{6})", css)
    text = re.findall(r"^  color: (#[\da-f]{6});", css, re.MULTILINE)
    return dict(zip(("active", "inactive"), zip(gradients, edges, text), strict=True))


def xml(element):
    ET.indent(element, space="  ")
    return GENERATED + "\n" + ET.tostring(element, encoding="unicode") + "\n"


def svg(width, height, scale):
    return ET.Element(f"{{{SVG}}}svg", {
        "width": str(width * scale), "height": str(height * scale),
        "viewBox": f"0 0 {width} {height}",
    })


def graphic(parent, tag, **attributes):
    return ET.SubElement(parent, f"{{{SVG}}}{tag}", attributes)


def button_art(parent, name, state, x=0, y=0):
    art = graphic(parent, "g", transform=f"translate({x} {y})")
    fill = {"active": "#3d3e40", "inactive": "#303133",
            "prelight": "#343537", "pressed": "#242527"}[state]
    engaged = state in ("prelight", "pressed")
    path, ink, outline = BUTTONS.get(name, (EXTRA_GLYPHS.get(name), "#c5c6c7", "#171819"))
    graphic(art, "circle", cx="6", cy="6", r="4.75", fill=fill,
            stroke=outline if engaged else "#18191a", **{"stroke-width": "1"})
    if path and (engaged or name == "menu"):
        graphic(art, "path", d=path, fill="none", stroke=ink,
                **{"stroke-width": "1.4", "stroke-linecap": "butt", "stroke-linejoin": "miter"})


def button_svg(name, state):
    icon = svg(GLYPH, GLYPH, 4)
    button_art(icon, name, state)
    return xml(icon)


def title_art(root, colors, width, corner=None):
    (top, bottom), (shine, edge), _ = colors
    defs = graphic(root, "defs")
    gradient = graphic(defs, "linearGradient", id="bar", x2="0", y2="1")
    for offset, color in (("0", shine), (".03125", shine), (".03125", top),
                          (".96875", bottom), (".96875", edge), ("1", edge)):
        graphic(gradient, "stop", offset=offset, **{"stop-color": color})
    if corner == "left":
        graphic(root, "path", d=f"M0 {HEIGHT}V4Q0 0 4 0H{width}V{HEIGHT}Z", fill="url(#bar)")
    elif corner == "right":
        graphic(root, "path", d=f"M0 0H{width - 4}Q{width} 0 {width} 4V{HEIGHT}H0Z",
                fill="url(#bar)")
    else:
        graphic(root, "rect", width=str(width), height=str(HEIGHT), fill="url(#bar)")


def xfwm_frames(colors, scale):
    normal, inactive = colors["active"], colors["inactive"]
    for state, palette in colors.items():
        strip = svg(1, HEIGHT, scale)
        title_art(strip, palette, 1)
        for segment in range(1, 6):
            yield f"title-{segment}-{state}.svg", xml(strip)
        for side in ("left", "right"):
            corner = svg(4, HEIGHT, scale)
            title_art(corner, palette, 4, side)
            yield f"top-{side}-{state}.svg", xml(corner)
        border = svg(2, 2, scale)
        graphic(border, "rect", width="2", height="2", fill=palette[1][1])
        for part in ("left", "right", "bottom", "bottom-left", "bottom-right"):
            yield f"{part}-{state}.svg", xml(border)

    for control, names in {
        "close": ("close",), "hide": ("minimize",), "maximize": ("maximize", "restore"),
        "menu": ("menu",), "shade": ("shade", "unshade"), "stick": ("stick", "unstick"),
    }.items():
        for index, name in enumerate(names):
            for state in ("active", "inactive", "prelight", "pressed"):
                icon = svg(BUTTON, HEIGHT, scale)
                title_art(icon, inactive if state == "inactive" else normal, BUTTON)
                button_art(icon, name, state, (BUTTON - GLYPH) // 2, (HEIGHT - GLYPH) // 2)
                prefix = "toggled-" if index else ""
                yield f"{control}-{prefix}{state}.svg", xml(icon)

    yield "themerc", (
        "# Generated by tools/build.py.\n"
        f"active_text_color={normal[2]}\ninactive_text_color={inactive[2]}\n"
        "title_shadow_active=false\ntitle_shadow_inactive=false\n"
        "title_alignment=center\nfull_width_title=true\nshow_app_icon=false\n"
        f"button_offset={scale}\nmaximized_offset={5 * scale}\n"
        "button_spacing=0\nframe_border_top=0\n"
    )


def marco_frame(colors):
    theme = ET.Element("metacity_theme")
    info = ET.SubElement(theme, "info")
    for tag, value in {"name": "Apartment Blue", "author": "Apartment Blue contributors",
                       "copyright": "GPL-3.0-or-later", "date": "2026",
                       "description": "Charcoal title bars with recessed graphite buttons."}.items():
        ET.SubElement(info, tag).text = value

    geometry = ET.SubElement(theme, "frame_geometry", name="normal", title_scale="medium",
                             rounded_top_left="4", rounded_top_right="4")
    for name, value in {"left_width": 2, "right_width": 2, "bottom_height": 2,
                        "left_titlebar_edge": 5, "right_titlebar_edge": 5, "button_width": BUTTON,
                        "button_height": BUTTON, "title_vertical_pad": 0}.items():
        ET.SubElement(geometry, "distance", name=name, value=str(value))
    ET.SubElement(geometry, "border", name="title_border", left="4", right="4", top="0", bottom="0")
    pad = str((HEIGHT - BUTTON) // 2)
    ET.SubElement(geometry, "border", name="button_border", left="0", right="0", top=pad, bottom=pad)
    maximized = ET.SubElement(theme, "frame_geometry", name="maximized", parent="normal",
                              rounded_top_left="0", rounded_top_right="0")
    for name in ("left_width", "right_width", "bottom_height"):
        ET.SubElement(maximized, "distance", name=name, value="0")
    ET.SubElement(theme, "frame_geometry", name="border", parent="normal", has_title="false",
                  hide_buttons="true", rounded_top_left="0", rounded_top_right="0")

    border = ET.SubElement(theme, "draw_ops", name="border")
    ET.SubElement(border, "rectangle", x="0", y="0", width="width", height="height",
                  color=colors["active"][1][1], filled="true")
    for state, ((top, bottom), (shine, edge), text) in colors.items():
        bar = ET.SubElement(theme, "draw_ops", name=f"bar_{state}")
        gradient = ET.SubElement(bar, "gradient", type="vertical", x="0", y="0",
                                 width="width", height="height")
        for color in (top, bottom):
            ET.SubElement(gradient, "color", value=color)
        for y, color in (("0", shine), ("height - 1", edge)):
            ET.SubElement(bar, "rectangle", x="0", y=y, width="width", height="1",
                          color=color, filled="true")
        title = ET.SubElement(theme, "draw_ops", name=f"title_{state}")
        ET.SubElement(title, "title", x="(width - title_width) / 2",
                      y="(height - title_height) / 2", color=text)

    icons = {state: f"../titlebuttons/{state}.svg" for state in ("rest", "unfocused")}
    icons.update({name: f"{name}.svg" for name in (*CONTROLS, "restore")})
    icons.update({f"{name}_pressed": f"../titlebuttons/{name}-pressed.svg" for name in BUTTONS})
    for name, filename in icons.items():
        ops = ET.SubElement(theme, "draw_ops", name=name)
        ET.SubElement(ops, "image", filename=filename, x="(width - 12) / 2", y="(height - 12) / 2",
                      width="12", height="12")

    for state in colors:
        style = ET.SubElement(theme, "frame_style", name=state, geometry="normal")
        for piece, ops in (("entire_background", "border"), ("titlebar", f"bar_{state}"),
                           ("title", f"title_{state}")):
            ET.SubElement(style, "piece", position=piece, draw_ops=ops)
        for control in CONTROLS:
            for event in ("normal", "prelight", "pressed"):
                art = control
                if event == "normal" and control != "menu":
                    art = "rest" if state == "active" else "unfocused"
                elif event == "pressed" and control in BUTTONS:
                    art = f"{control}_pressed"
                ET.SubElement(style, "button", function=control, state=event, draw_ops=art)
        style = ET.SubElement(theme, "frame_style", name=f"maximized_{state}",
                              geometry="maximized", parent=state)
        for event in ("prelight", "pressed"):
            art = "restore_pressed" if event == "pressed" else "restore"
            ET.SubElement(style, "button", function="maximize", state=event, draw_ops=art)
    ET.SubElement(theme, "frame_style", name="border", geometry="border", parent="inactive")

    for kind in ("normal", "border"):
        styles = ET.SubElement(theme, "frame_style_set", name=kind)
        for state, focus in (("active", "yes"), ("inactive", "no")):
            for mode in ("normal", "shaded", "maximized", "maximized_and_shaded"):
                name = f"maximized_{state}" if mode.startswith("maximized") else state
                attrs = {"resize": "both"} if mode == "normal" else {}
                ET.SubElement(styles, "frame", focus=focus, state=mode,
                              style=name if kind == "normal" else "border", **attrs)
    for kind in ("normal", "dialog", "modal_dialog", "menu", "utility", "border"):
        ET.SubElement(theme, "window", type=kind, style_set="border" if kind == "border" else "normal")
    return xml(theme)


def native_frames(theme):
    colors = title_colors(theme)
    for filename, state in (("rest", "active"), ("unfocused", "inactive")):
        yield f"Apartment-Blue/titlebuttons/{filename}.svg", button_svg(None, state)
    for name in BUTTONS:
        yield f"Apartment-Blue/titlebuttons/{name}.svg", button_svg(name, "prelight")
        yield f"Apartment-Blue/titlebuttons/{name}-pressed.svg", button_svg(name, "pressed")
    yield "Apartment-Blue/metacity-1/metacity-theme-3.xml", marco_frame(colors)
    for name in (*CONTROLS, "restore"):
        yield f"Apartment-Blue/metacity-1/{name}.svg", button_svg(name, "prelight")
    for folder, scale in (("Apartment-Blue", 1), ("Apartment-Blue-HiDPI", 2)):
        for name, content in xfwm_frames(colors, scale):
            yield f"{folder}/xfwm4/{name}", content
